// Read-only integrity check reused from A94; this is not appearance approval.
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const crypto = require('node:crypto')
const zlib = require('node:zlib')
const read = name => JSON.parse(fs.readFileSync(path.join(__dirname, name)))
const sha = bytes => crypto.createHash('sha256').update(bytes).digest('hex')
const manifest = read('copy-manifest.json'), record = read('execution-record.json')
assert.equal(manifest.old_files_changed, 0)
assert.equal(manifest.copies.length, 30)
for (const item of manifest.copies) {
  const bytes = fs.readFileSync(path.join(__dirname, item.file))
  assert.equal(bytes.length, item.bytes)
  assert.equal(sha(bytes), item.sha256)
  assert.equal(sha(item.file.endsWith('.gz') ? zlib.gunzipSync(bytes) : bytes), item.decoded_sha256)
  if (item.file.endsWith('.png')) assert.equal(bytes.subarray(0, 8).toString('hex'), '89504e470d0a1a0a')
}
assert.equal(manifest.copies.filter(x => x.file.endsWith('.png')).length, 20)
assert.equal(manifest.copies.filter(x => x.file.endsWith('.gz')).length, 7)
assert.equal(record.directly_viewed.length, 14)
assert.equal(new Set(record.directly_viewed).size, 14)
for (const file of record.directly_viewed) assert(manifest.copies.some(x => x.file === file))
const root = path.resolve(__dirname, '../../../../..')
assert.equal(record.unchanged_files.length, 8)
for (const item of record.unchanged_files) assert.equal(sha(fs.readFileSync(path.join(root, item.file))), item.sha256)
for (const run of ['first', 'corrected']) {
  const browser = read(run + '-browser.json')
  assert.deepEqual(browser.errors, [])
  assert.deepEqual(browser.stats, record.browser[run])
  assert.equal(browser.stats.expected, 4)
  for (const key of ['skipped', 'unexpected', 'flaky']) assert.equal(browser.stats[key], 0)
  const results = browser.suites.flatMap(s => s.specs.flatMap(x => x.tests.flatMap(t => t.results)))
  assert.equal(results.length, 4)
  assert(results.every(r => r.status === 'passed' && r.errors.length === 0))
  const attachments = results.flatMap(r => r.attachments || [])
  for (const a of attachments.filter(a => a.name.endsWith('-native-asset'))) {
    const asset = JSON.parse(Buffer.from(a.body, 'base64'))
    const item = record.unchanged_files.find(x => x.file.endsWith('/' + asset.filename))
    assert.equal(asset.sha256, item.sha256)
  }
  const isolation = attachments.filter(a => a.name.endsWith('-surface-isolation'))
  assert.equal(isolation.length, 2)
  for (const a of isolation) {
    const rows = JSON.parse(Buffer.from(a.body, 'base64'))
    assert.deepEqual(rows.map(x => [x.mode, x.close]), [['baseline', false], ['body-only', false], ['baseline', true], ['body-only', true]])
    const attributes = rows[0].meshes.map(m => m.attributes)
    for (const row of rows) {
      assert.equal(row.body_count, 2)
      assert.equal(row.boundary_count, 8)
      assert.equal(row.meshes.length, 10)
      assert.equal(row.meshes.filter(m => m.visible).length, row.mode === 'baseline' ? 10 : 2)
      assert(row.meshes.every(m => m.receiveShadow === false))
      assert.deepEqual(row.meshes.map(m => m.attributes), attributes)
    }
  }
}
const native = read('forearm-diagnosis.json')
assert.deepEqual(native.checks.map(x => [x.stage, x.gender, x.flat_faces, x.narrow_faces, x.over_5mm_over_1rad_edges]), [['source', 'Male', 0, 217, 133], ['source', 'Female', 0, 220, 123], ['import', 'Male', 0, 471, 136], ['import', 'Female', 0, 489, 136]])
for (const key of ['files_saved', 'coordinates_changed', 'new_glb', 'full_deformation_qa', 'appearance_approved']) assert.equal(native[key], false)
assert.equal(record.style.initial_typecheck_exit, 2)
assert.equal(record.style.initial_typescript_errors, 6)
for (const key of ['corrected_typecheck_exit', 'restored_typecheck_exit', 'formatted_check_exit', 'native_ruff_check_exit', 'native_isolated_format_check_exit']) assert.equal(record.style[key], 0)
assert(record.runs.every(r => r.exit_code === 0))
assert(record.temporary_test_helpers_restored)
assert.equal(record.new_blend_files, 0)
assert.equal(record.new_glb_files, 0)
for (const key of ['new_full_deformation_qa', 'human_camera_capture', 'human_coordinate_collection', 'appearance_passed', 'adopted', 'release_approved', 'stages_1_to_6_complete', 'pr9_merge_allowed']) assert.equal(record[key], false)
