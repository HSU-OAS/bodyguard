// Read-only A92 diagnosis check, using the A91 integrity pattern. Not model approval.
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const crypto = require('node:crypto')
const zlib = require('node:zlib')
const read = name => JSON.parse(fs.readFileSync(path.join(__dirname, name)))
const sha = bytes => crypto.createHash('sha256').update(bytes).digest('hex')
const manifest = read('copy-manifest.json'), record = read('execution-record.json')
assert.equal(manifest.copies.length, 14)
assert.equal(manifest.old_files_changed, 0)
for (const item of manifest.copies) {
  const bytes = fs.readFileSync(path.join(__dirname, item.file))
  assert.equal(bytes.length, item.bytes)
  assert.equal(sha(bytes), item.sha256)
  assert.equal(sha(item.file.endsWith('.gz') ? zlib.gunzipSync(bytes) : bytes), item.decoded_sha256)
}
assert.equal(sha(fs.readFileSync(path.join(__dirname, '../../bodyguard_avatar_candidate_a91_rejected.blend'))), record.source_sha256)
assert.equal(manifest.copies.filter(x => x.file.endsWith('.gz')).length, 7)
for (const name of ['source-connectivity.json', 'import-connectivity.json', 'stage-diagnosis.json', 'duplicate-face-diagnosis.json', 'constrained-dryrun.json']) {
  const report = read(name)
  assert.equal(report.source_saved, false)
  assert.equal(report.full_qa, false)
  assert.equal(report.appearance_approval, false)
}
assert.deepEqual(read('source-connectivity.json').rows.map(x => x.long_folded_edges), [49, 50])
assert.deepEqual(read('import-connectivity.json').rows.map(x => x.long_folded_edges), [57, 48])
const female = read('stage-diagnosis.json').rows.find(x => x.body === 'Female')
assert.deepEqual(female.stages.map(x => x.nonmanifold_edges), [0, 1, 1])
assert.deepEqual(female.stages[1].bad_edge_radial_counts, { '4': 1 })
const corrected = read('constrained-dryrun.json')
assert.equal(corrected.input_sha256, record.source_sha256)
assert.deepEqual(corrected.rows.map(x => [x.before_long_folds, x.after_local_rotation_long_folds]), [[49, 48], [50, 47]])
assert(corrected.rows.every(x => x.all_vertex_coordinates_exact && x.outside_face_connectivity_exact && x.nonmanifold_edges === 0))
assert.deepEqual(corrected.rows[1].constrained_native_quads, [{ vertices: [103690, 68956, 103697, 103689], method: 'ALTERNATE' }])
assert.equal(record.runs.length, 7)
assert.deepEqual(record.runs.filter(x => x.exit_code === 1).map(x => x.name), ['unconstrained-ngon-test', 'constrained-native-enum-first'])
assert(record.runs.every(x => !x.source_saved && [0, 1].includes(x.exit_code)))
for (const key of ['source_full_qa_rerun', 'import_full_qa_rerun', 'browser_rerun', 'appearance_passed', 'stages_1_to_6_complete', 'release_approved', 'pr9_merge_allowed']) assert.equal(record[key], false)
for (const key of ['new_blend', 'new_glb', 'new_png', 'actual_camera_runs', 'old_assets_or_evidence_changed']) assert.equal(record[key], 0)
console.log(JSON.stringify({ integrity_passed: true, copies: 14, gzip: 7, native_runs: 7, native_failed: 2, new_saved_models: 0, full_qa: false, appearance_passed: false }))
