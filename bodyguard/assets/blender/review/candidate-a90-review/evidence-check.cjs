// Read-only, repeatable check of the preserved native evidence; not an appearance approval.
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const crypto = require('node:crypto')
const zlib = require('node:zlib')
const here = __dirname
const read = name => JSON.parse(fs.readFileSync(path.join(here, name)))
const manifest = read('copy-manifest.json')
const record = read('execution-record.json')
const sha = bytes => crypto.createHash('sha256').update(bytes).digest('hex')
assert.equal(manifest.old_files_changed, 0)
assert.equal(manifest.copies.length, 94)
for (const item of manifest.copies) {
  const bytes = fs.readFileSync(path.join(here, item.file))
  assert.equal(bytes.length, item.bytes)
  assert.equal(sha(bytes), item.sha256)
  assert.equal(sha(item.file.endsWith('.gz') ? zlib.gunzipSync(bytes) : bytes), item.decoded_sha256)
  if (item.file.endsWith('.png')) assert.equal(bytes.subarray(0, 8).toString('hex'), '89504e470d0a1a0a')
}
assert.equal(manifest.copies.filter(x => x.file.endsWith('.png')).length, 76)
for (const name of ['source-deformation.json', 'roundtrip-deformation.json']) {
  const result = read(name)
  assert(result.passed && result.rendered && result.candidate)
  assert.equal(result.checks.length, 121)
  const poses = result.checks.filter(x => 'edge_ratio_max' in x)
  assert.equal(poses.length, 118)
  assert(poses.every(x => Number.isFinite(x.edge_ratio_max) && x.edge_ratio_max < 3))
  assert.deepEqual(result.failures, [])
}
const preservation = read('saved-preservation.json')
assert(preservation.passed && !preservation.source_saved)
assert(preservation.rows.every(x => x.whole_topology_named_skin_hands_163_rest_bones_matrices_identical && x.front_and_above_neck_entire_surface_exact && x.maximum_artist_displacement_m < .006))
const paired = read('paired-original-edges.json')
assert.equal(paired.full_qa, false)
assert(paired.checks.every(x => x.edge_membership_and_original_length_class_locked))
assert.deepEqual(paired.checks.filter(x => x.region === 'neck').map(x => [x.before_long, x.after_long]), [[103, 104], [85, 89]])
for (const gender of ['male', 'female']) {
  const bytes = fs.readFileSync(path.join(here, 'bodyguard-' + gender + '-candidate.glb'))
  assert.equal(bytes.toString('ascii', 0, 4), 'glTF')
  assert.equal(bytes.readUInt32LE(8), bytes.length)
  const gltf = JSON.parse(bytes.toString('utf8', 20, 20 + bytes.readUInt32LE(12)))
  assert.equal(gltf.skins.length, 1)
  assert.equal(gltf.skins[0].joints.length, 163)
  assert.equal(gltf.meshes.length, 5)
  assert.equal(gltf.images?.length || 0, 0)
  assert.equal(gltf.animations?.length || 0, 0)
}
const browser = read('browser-report.json')
assert.equal(browser.stats.expected, 3)
for (const field of ['skipped', 'unexpected', 'flaky']) assert.equal(browser.stats[field], 0)
assert.equal(browser.stats.duration, record.browser.duration)
assert.equal(record.runs.length, 11)
assert.equal(record.runs.filter(x => x.exit_code === 1).length, 1)
assert(record.runs.every(x => x.exit_code === 0 || x.name === 'professional-surface-probe-first'))
assert.equal(record.directly_viewed.total, Object.values(record.directly_viewed).filter(Array.isArray).reduce((n, files) => n + files.length, 0))
for (const key of ['appearance_passed', 'release_approved', 'stages_1_to_6_complete', 'pr9_merge_allowed']) assert.equal(record[key], false)
assert.equal(record.actual_png.total, 76)
console.log(JSON.stringify({ integrity_passed: true, copies: 94, png: 76, directly_viewed: 40, source_and_import_deformations: 118, actual_Chrome: 3, native_failed_probe: 1, appearance_passed: false, release_approved: false }))
