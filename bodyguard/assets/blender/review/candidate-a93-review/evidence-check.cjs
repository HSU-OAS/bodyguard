// Read-only check adapted from A91. Evidence integrity is not appearance approval.
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const crypto = require('node:crypto')
const zlib = require('node:zlib')
const read = name => JSON.parse(fs.readFileSync(path.join(__dirname, name)))
const manifest = read('copy-manifest.json'), record = read('execution-record.json')
const sha = bytes => crypto.createHash('sha256').update(bytes).digest('hex')
assert.equal(manifest.old_files_changed, 0)
assert.equal(manifest.copies.length, 89)
for (const item of manifest.copies) {
  const bytes = fs.readFileSync(path.join(__dirname, item.file))
  assert.equal(bytes.length, item.bytes)
  assert.equal(sha(bytes), item.sha256)
  assert.equal(sha(item.file.endsWith('.gz') ? zlib.gunzipSync(bytes) : bytes), item.decoded_sha256)
  if (item.file.endsWith('.png')) assert.equal(bytes.subarray(0, 8).toString('hex'), '89504e470d0a1a0a')
}
assert.equal(manifest.copies.filter(x => x.file.endsWith('.png')).length, 74)
assert.equal(manifest.copies.filter(x => x.file.endsWith('.gz')).length, 4)
assert.equal(sha(fs.readFileSync(path.join(__dirname, '../../bodyguard_avatar_candidate_a91_rejected.blend'))), record.input_sha256)
assert.equal(manifest.copies[0].sha256, record.output_sha256)
const root = path.resolve(__dirname, '../../../../..')
for (const helper of record.unchanged_helpers) assert.equal(sha(fs.readFileSync(path.join(root, helper.file))), helper.sha256)
for (const name of ['source-deformation.json', 'roundtrip-deformation.json']) {
  const result = read(name)
  assert(result.passed && result.rendered && result.candidate)
  assert.equal(result.checks.length, 121)
  const poses = result.checks.filter(x => 'edge_ratio_max' in x)
  assert.equal(poses.length, 118)
  assert(poses.every(x => Number.isFinite(x.edge_ratio_max) && x.edge_ratio_max < 3))
  assert.deepEqual(result.failures, [])
}
const native = read('native-connectivity.json'), saved = read('saved-preservation.json')
assert.equal(native.source_sha256, record.input_sha256)
assert.deepEqual(native.rows.map(x => [x.original_long_folds, x.final_long_folds]), [[49, 48], [50, 47]])
assert.deepEqual(native.rows.map(x => x.original_ngon_sizes.reduce((n, size) => n + size - 3, 0)), [5, 37])
assert.deepEqual(native.rows[1].constrained_native_quads, [{ vertices: [103690, 68956, 103697, 103689], method: 'ALTERNATE' }])
assert(saved.passed && !saved.source_saved && !saved.full_qa)
assert.deepEqual(saved.rows.map(x => [x.body, x.changed_faces_removed, x.changed_faces_added]), [['Male', 10, 15], ['Female', 19, 56]])
saved.rows.forEach((x, i) => {
  assert(x.all_vertex_coordinates_named_skin_bones_matrices_hands_exact && x.outside_face_connectivity_winding_exact && x.original_vertices_preserved && x.bones === 163 && x.geometry_displacement_m === 0)
  const extra = native.rows[i].extra_edges_and_faces
  assert.equal(x.extra_edges_and_faces_from_frozen_polygon_sizes, extra)
  assert.equal(x.edges_before_after[1] - x.edges_before_after[0], extra)
  assert.equal(x.faces_before_after[1] - x.faces_before_after[0], extra)
})
for (const gender of ['male', 'female']) {
  const bytes = fs.readFileSync(path.join(__dirname, 'bodyguard-' + gender + '-candidate.glb'))
  assert.equal(bytes.toString('ascii', 0, 4), 'glTF')
  assert.equal(bytes.readUInt32LE(8), bytes.length)
  const gltf = JSON.parse(bytes.toString('utf8', 20, 20 + bytes.readUInt32LE(12)))
  assert.equal(gltf.skins.length, 1)
  assert.equal(gltf.skins[0].joints.length, 163)
  assert.equal(gltf.meshes.length, 5)
  for (const key of ['images', 'animations', 'cameras']) assert.equal(gltf[key]?.length || 0, 0)
}
const browser = read('browser-report.json')
assert.deepEqual(browser.errors, [])
assert.deepEqual(browser.stats, record.browser)
assert.equal(browser.stats.expected, 3)
for (const key of ['skipped', 'unexpected', 'flaky']) assert.equal(browser.stats[key], 0)
const results = browser.suites.flatMap(x => x.specs.flatMap(x => x.tests.flatMap(x => x.results)))
assert.equal(results.length, 3)
assert(results.every(x => x.status === 'passed' && x.errors.length === 0))
for (const a of results.flatMap(x => x.attachments || []).filter(x => x.name.endsWith('-native-asset'))) {
  const asset = JSON.parse(Buffer.from(a.body, 'base64'))
  const item = manifest.copies.find(x => x.file === asset.filename)
  assert.equal(asset.sha256, item.sha256)
  assert.equal(asset.bytes, item.bytes)
}
assert.equal(record.runs.length, 9)
assert.deepEqual(record.runs.filter(x => x.exit_code === 1).map(x => x.name), ['source-path-preflight', 'export-path-preflight', 'browser-sandbox-preflight'])
assert.equal(record.runs.find(x => x.name === 'actual-Chrome').all_native_actors_terminal_before_browser, true)
assert.equal(read('native-path-preflight.json').source.exit_code, 1)
assert.equal(read('native-path-preflight.json').export.exit_code, 1)
assert.equal(read('browser-sandbox-preflight.json').chrome_launched, false)
assert.equal(record.style.backend_cwd_format_exit, 1)
assert.equal(record.style.new_python_isolated_format_exit, 0)
assert.equal(record.directly_viewed.total, Object.values(record.directly_viewed).filter(Array.isArray).reduce((n, files) => n + files.length, 0))
assert.equal(record.directly_viewed.total, 38)
for (const key of ['appearance_passed', 'release_approved', 'stages_1_to_6_complete', 'pr9_merge_allowed', 'adopted']) assert.equal(record[key], false)
assert.equal(record.actual_png.total, 74)
console.log(JSON.stringify({ integrity_passed: true, copies: 89, png: 74, directly_viewed: 38, source_and_import_deformations: 118, actual_Chrome: 3, helper_path_failures: 2, failed_browser_preflight: 1, appearance_passed: false, release_approved: false }))
