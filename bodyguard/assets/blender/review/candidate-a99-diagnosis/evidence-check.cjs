 assert.deepEqual(x.rows.map(r=>r.after.long_fold_edges),folds)
 assert(x.rows.every(r=>r.retained_coordinates_skin_hands_guard_passed&&r.rest_bones_matrices_preserved&&r.after.global_nonmanifold===0))
