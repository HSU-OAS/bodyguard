// Archive integrity only; not a camera, pose or clinical test.
const assert = require('node:assert/strict')
const { readFileSync } = require('node:fs')
const { resolve, join } = require('node:path')
const { createHash } = require('node:crypto')
const { gunzipSync } = require('node:zlib')
const root = resolve(__dirname, '../../../..')
const json = (name) => JSON.parse(readFileSync(join(__dirname, name), 'utf8'))
const sha = (bytes) => createHash('sha256').update(bytes).digest('hex')
const record = json('execution-record.json')
for (const source of record.source_hashes) {
  assert.equal(sha(readFileSync(join(root, source.path))), source.sha256, source.path)
}
const old = json('original-selection-sha256.json')
assert.equal(old.length, 20)
for (const source of old) assert.equal(sha(readFileSync(join(root, source.path))), source.sha256, source.path)
const copies = json('copy-manifest.json')
assert.equal(copies.length, 8)
assert.equal(copies.filter((v) => v.path.endsWith('.png')).length, 6)
for (const source of copies) {
  const bytes = readFileSync(join(__dirname, source.path))
  assert.equal(bytes.length, source.bytes, source.path)
  assert.equal(sha(bytes), source.sha256, source.path)
}
const browser = JSON.parse(gunzipSync(readFileSync(join(__dirname, 'browser-report.json.txt.gz'))))
assert.equal(browser.stats.expected, 5)
for (const key of ['unexpected', 'flaky', 'skipped']) assert.equal(browser.stats[key], 0)
const specs = browser.suites.flatMap((suite) => suite.specs)
assert.equal(specs.length, 5)
for (const spec of specs) {
  assert.equal(spec.tests.length, 1)
  assert.equal(spec.tests[0].results.length, 1)
  const result = spec.tests[0].results[0]
  assert.equal(result.status, 'passed')
  const observation = result.attachments.find((v) => v.name === 'observations.json')
  assert(observation)
  const value = JSON.parse(Buffer.from(observation.body, 'base64'))
  assert.equal(value.cameraCalls, 0)
  assert.equal(value.actualAuthServer, false)
  assert.equal(value.actualHumanCamera, false)
  assert.deepEqual(value.storageLengths, [0, 0])
  assert.deepEqual(value.pageErrors, [])
  for (const path of value.apiPaths) assert(['/api/v1/me', '/api/v1/auth/google/status'].includes(path))
}
assert.equal(record.runs.initial_missing_module[0].exit_code, 1)
assert.match(record.runs.initial_missing_module[0].output, /Cannot find module/)
assert.equal(record.runs.adversarial_red_55.exit_code, 1)
assert.match(record.runs.adversarial_red_55.output, /4 failed/)
assert.equal(record.runs.malformed_end_red_60.exit_code, 1)
assert.match(record.runs.malformed_end_red_60.output, /1 failed/)
assert.equal(record.runs.malformed_end_green_60.exit_code, 0)
assert.match(record.runs.malformed_end_green_60.output, /60 passed/)
for (const run of record.runs.final_local_198_biome_typecheck) assert.equal(run.exit_code, 0)
assert.match(record.runs.final_local_198_biome_typecheck[0].output, /198 passed/)
assert.equal(record.runs.final_production_and_chrome.at(-1).exit_code, 0)
assert.match(record.runs.final_production_and_chrome.at(-1).output, /5 passed/)
assert.match(record.runs.final_production_and_chrome.at(-1).output, /unconnected_coaching_engine_strings.*0/)
const engine = readFileSync(join(root, 'bodyguard/frontend/src/stretch/progression.ts'), 'utf8')
assert(!/^import\s/m.test(engine), 'Kernel must remain independent of DOM/camera/API/storage')
assert.equal(record.actuals.actual_human_trials, 0)
assert.equal(record.stage_passed, false)
console.log(JSON.stringify({source_SHA_checked:3,original_selection_files_unchanged:old.length,
  archived_copies:copies.length,PNG:6,chrome_expected:5,engine_synthetic:60,vitest_total:198,
  actual_camera:0,whole_stage_passed:false}))
