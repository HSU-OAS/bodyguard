const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {chromium}=require(require.resolve('@playwright/test',{paths:[path.resolve('bodyguard/frontend')]}));
const [url,output]=process.argv.slice(2);
(async()=>{
 fs.mkdirSync(output,{recursive:true});
 const browser=await chromium.launch({channel:'chrome',headless:true});
 try {
 const context=await browser.newContext({viewport:{width:1440,height:960},serviceWorkers:'block'});
 const errors=[],failed=[];
 const page=await context.newPage();
 page.on('pageerror',e=>errors.push(e.message));
 page.on('response',r=>{if(r.status()>=400)failed.push({status:r.status(),url:r.url()})});
 await page.goto(url,{waitUntil:'networkidle'});
 await page.getByRole('button',{name:'목 옆 늘리기',exact:true}).waitFor();
 assert.equal(await page.getByRole('link',{name:'내 계정',exact:true}).count(),0);
 await page.screenshot({path:path.join(output,'home-1440.png')});
 const geometry=await page.evaluate(()=>{
  const rect=s=>{const r=document.querySelector(s).getBoundingClientRect();return {x:r.x,y:r.y,width:r.width,height:r.height}};
  return {left:rect('.figma-left'),right:rect('.figma-right'),stage:rect('.figma-stage'),scrollWidth:document.documentElement.scrollWidth,viewport:innerWidth,assets:[...document.images].map(i=>({source:i.getAttribute('src'),loaded:i.complete&&i.naturalWidth>0}))};
 });
 assert.equal(geometry.scrollWidth,geometry.viewport);
 assert.equal(geometry.left.x,40);assert.equal(geometry.left.y,150);assert.equal(geometry.left.width,264);
 assert.equal(geometry.right.x,1010);assert.equal(geometry.right.y,150);assert.equal(geometry.right.width,390);
 assert(geometry.assets.every(a=>a.loaded));
 await page.getByRole('button',{name:'서비스 메뉴 접기',exact:true}).click();
 await page.getByRole('button',{name:'서비스 메뉴 펼치기',exact:true}).click();
 await page.getByRole('button',{name:'동작 목록 접기',exact:true}).click();
 await page.getByRole('button',{name:'동작 목록 펼치기',exact:true}).click();
 const preview=page.getByRole('group',{name:'목 옆 늘리기 미리보기',exact:true});
 await preview.hover();
 const movie=page.getByLabel('목 옆 늘리기 동작 영상',{exact:true});
 await page.waitForFunction(()=>{const v=document.querySelector('video[aria-label="목 옆 늘리기 동작 영상"]');return v&&!v.paused&&v.currentTime>0;});
 await page.mouse.move(10,10);
 await page.waitForFunction(()=>document.querySelector('video[aria-label="목 옆 늘리기 동작 영상"]').paused);
 await page.getByRole('button',{name:'목 옆 늘리기',exact:true}).click();
 assert.match(await page.getByRole('link',{name:'웹캠 체험',exact:true}).getAttribute('href'),/inspection\.html\?motion=neck-side$/);
 await page.getByRole('link',{name:'웹캠 체험',exact:true}).click();
 await page.getByRole('button',{name:'웹캠 시작',exact:true}).waitFor();
 assert.equal(await page.locator('#detailed-hands').isChecked(),false);
 await page.getByRole('heading',{name:'목 옆 늘리기 · 웹캠 추종 체험',exact:true}).waitFor();
 assert.equal(await page.locator('#view').inputValue(),'upper');
 await page.screenshot({path:path.join(output,'inspection-ready-1440.png')});
 await page.getByRole('link',{name:'BODYGUARD',exact:true}).click();
 await page.setViewportSize({width:1024,height:768});
 await page.screenshot({path:path.join(output,'home-1024.png')});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),1024);
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.getByRole('group',{name:'목 옆 늘리기 미리보기',exact:true}).hover();
 assert(await page.getByLabel('목 옆 늘리기 동작 영상',{exact:true}).evaluate(v=>v.paused));
 fs.writeFileSync(path.join(output,'browser.json'),JSON.stringify({url,geometry,errors,failed,cameraStarted:false,hoverVideo:true,panelToggles:true,inspectionNavigation:true,reducedMotion:true},null,2)+'\n');
 assert.equal(errors.length,0,JSON.stringify(errors));assert.equal(failed.length,0,JSON.stringify(failed));
 console.log('PASS Figma geometry, local assets, panel controls, hover video, inspection navigation, 1024px, reduced motion; camera not started');
 } finally { await browser.close(); }
})().catch(e=>{console.error(e);process.exitCode=1});
